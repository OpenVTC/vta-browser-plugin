#!/usr/bin/env node
// Regenerate `src/rooms/confusables-data.ts` from Unicode's own `confusables.txt`
// (Unicode Technical Standard #39, *Unicode Security Mechanisms*, section 4) —
// the data `skeleton()` maps each character by.
//
//   npm run confusables:sync --workspace @openvtc/pnm-core
//   npm run confusables:sync --workspace @openvtc/pnm-core -- path/to/confusables.txt
//
// The data is the whole published file, not a selection: every mapping line is
// carried, and the file is checked against the SHA-256 recorded below before
// anything is written, so a regeneration either reproduces the committed module
// or fails. To move to a later Unicode version, change VERSION and SHA256 to
// the published file's, run this, and review the diff.
//
// Why a generated table rather than a package: no confusables package on npm
// is both maintained and a straight implementation of `skeleton()` over the
// published data, and the algorithm itself is four lines (`confusables.ts`).
// What has to be right is the data, and the data is Unicode's.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const VERSION = "16.0.0";
const URL = `https://www.unicode.org/Public/security/${VERSION}/confusables.txt`;
const SHA256 = "95bd0aad6dced5ebc63436f459c06ab21a8d107cd842fb57f5c3a1e91bca8611";
const OUT = join(resolve(import.meta.dirname, ".."), "src/rooms/confusables-data.ts");

const text = process.argv[2]
  ? readFileSync(resolve(process.argv[2]), "utf8")
  : await (async () => {
      const res = await fetch(URL, { signal: AbortSignal.timeout(60_000) });
      if (!res.ok) throw new Error(`${URL}: HTTP ${res.status}`);
      return res.text();
    })();

const digest = createHash("sha256").update(text, "utf8").digest("hex");
if (digest !== SHA256) {
  throw new Error(`confusables.txt ${VERSION} has SHA-256 ${digest}, not the ${SHA256} recorded here — refusing to write`);
}

const entries = [];
for (const raw of text.split("\n")) {
  const line = raw.replace(/#.*$/, "").trim();
  if (line === "") continue;
  const fields = line.split(";").map((f) => f.trim());
  if (fields.length < 3) throw new Error(`unreadable line: ${raw}`);
  const [source, target, type] = fields;
  // Since Unicode 9 every mapping is MA; anything else is a format change to look at.
  if (type !== "MA") throw new Error(`unexpected mapping type ${type}: ${raw}`);
  if (!/^[0-9A-F]{4,6}$/.test(source)) throw new Error(`unexpected source: ${raw}`);
  const targets = target.split(/\s+/);
  if (targets.some((t) => !/^[0-9A-F]{4,6}$/.test(t))) throw new Error(`unexpected target: ${raw}`);
  entries.push(`${source.replace(/^0+(?=.)/, "").toLowerCase()}:${targets.map((t) => t.replace(/^0+(?=.)/, "").toLowerCase()).join(" ")}`);
}
if (entries.length < 6000) throw new Error(`only ${entries.length} mappings — wrong file?`);

// Wrapped so the generated line lengths stay reviewable.
const chunks = [];
for (let i = 0; i < entries.length; i += 16) chunks.push(`  ${JSON.stringify(entries.slice(i, i + 16).join(","))},`);

writeFileSync(
  OUT,
  `// Generated by scripts/sync-confusables.mjs from Unicode's confusables.txt — DO NOT EDIT BY HAND.
// Source: ${URL}
// SHA-256: ${SHA256}
// © Unicode, Inc. Used under the Unicode License v3 (https://www.unicode.org/license.txt).
//
// One entry per mapping line, \`source:target\` in hexadecimal code points, the
// target a space-separated sequence. Read by \`confusables.ts\`.

/** The Unicode version of the confusables data. */
export const CONFUSABLES_VERSION = "${VERSION}";

/** The SHA-256 of the \`confusables.txt\` this was generated from. */
export const CONFUSABLES_SHA256 = "${SHA256}";

/** How many mappings the source file holds. */
export const CONFUSABLES_COUNT = ${entries.length};

/** The mappings, comma-separated, in chunks. */
export const CONFUSABLES_DATA: readonly string[] = [
${chunks.join("\n")}
];
`,
);
console.log(`wrote ${OUT}\n  Unicode ${VERSION}, ${entries.length} mappings`);
